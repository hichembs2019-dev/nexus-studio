"""Voice assignment per speaking character.

Owner's standing instruction, 2026-10-21 ("احذف الستة صور و قلت التوليد
حسب القصة" - delete the six photos, I told you generation must be
per-story): this module used to also resolve a character's PHOTO
(`resolve_placeholder_photo`, one of six generic illustrations under
assets/placeholder_characters/, picked by gender/age_group) - deleted
outright, along with those six image files and the script that drew
them (`generate_placeholder_avatars.py`). There is no generic/fixed
photo anywhere in this codebase any more, for any reason: every
character's real photo is generated by DialoguePipeline from its own
`appearance` text during production (see dialogue_pipeline.py), or that
character's lines fail and are reported - never a stand-in illustration.

Owner's instruction, 2026-10-19 ("اللهجة السورية المستخدمة في الدبلجة
كانت بيضاء ومفهومة جداً لجميع سكان شمال إفريقيا" - the Syrian dialect
used in [Turkish series] dubbing was "neutral" and very understandable
across all of North Africa): switched from Tunisian to Syrian voices for
exactly this reason - wider reach across the whole Arabic-speaking
audience this project is meant to publish to, not just Tunisia.
`ar-SY-AmanyNeural` (female) and `ar-SY-LaithNeural` (male) are both
real, live-verified Syrian Arabic Azure voices, Status "GA", confirmed
the same way the Tunisian ones were (a real `GET .../voices/list` against
this project's own Azure resource, docs/SOURCES.md "Language and visual
style") - not a guess, and not assumed from the general region table.
This voice choice is unaffected by the photo deletion above - it is a
property of the character's own name/speaking role, not their face.
"""
from __future__ import annotations

_VOICE_BY_GENDER = {
    "male": "ar-SY-LaithNeural",
    "female": "ar-SY-AmanyNeural",
}


def resolve_placeholder_voice(gender: str) -> str:
    gender = gender.strip().lower()
    return _VOICE_BY_GENDER.get(gender, _VOICE_BY_GENDER["male"])
