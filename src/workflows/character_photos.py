"""Owner's instruction, 2026-10-19 ("الصور طبعا افتراضية... مجموعة صور
افتراضية جاهزة (رجل/امرأة بأعمار مختلفة)، تُسند تلقائيًا حسب وصف كل
شخصية" - the photos are of course placeholders, a ready set of
placeholder photos (man/woman, different ages), assigned automatically
per character description): DialoguePipeline refuses to invent a face
(see models.py's Character docstring), so every character needs a real
reference_image_path before any real generation - but the owner does not
want to upload a photo per character either. These six images
(assets/placeholder_characters/) are original illustrations generated by
this project itself (src/workflows/generate_placeholder_avatars.py), not
real people - no likeness/copyright question to verify, unlike a
real-person stock photo would raise.

Voices: `ar-TN-ReemNeural` (female) and `ar-TN-HediNeural` (male) are
both real, live-verified Tunisian Arabic Azure voices for this project's
own subscription (docs/SOURCES.md "Azure TTS") - not a guess.
"""
from __future__ import annotations

import os

_ASSETS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(__file__))), "assets", "placeholder_characters")

_VALID_GENDERS = ("male", "female")
_VALID_AGE_GROUPS = ("young", "middle", "older")

_VOICE_BY_GENDER = {
    "male": "ar-TN-HediNeural",
    "female": "ar-TN-ReemNeural",
}


def resolve_placeholder_photo(gender: str, age_group: str) -> str:
    gender = gender.strip().lower()
    age_group = age_group.strip().lower()
    if gender not in _VALID_GENDERS:
        gender = "male"
    if age_group not in _VALID_AGE_GROUPS:
        age_group = "middle"
    return os.path.join(_ASSETS_DIR, f"{gender}_{age_group}.png")


def resolve_placeholder_voice(gender: str) -> str:
    gender = gender.strip().lower()
    return _VOICE_BY_GENDER.get(gender, _VOICE_BY_GENDER["male"])
