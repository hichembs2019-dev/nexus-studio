"""Kling's official API as a third `ReplicateVideoClient`: one photo + one
TTS clip in, one mp4 out - but with real body/camera motion, which the
Wan S2V paths cannot do (owner's real 2026-10-24 run: static camera,
almost no body motion - see docs/SOURCES.md).

Owner's choice, 2026-10-25 (decision card "كود Kling للحركة والشفاه"),
after the plan's claims were checked against Kling's own docs. NOT run
against the real API by this code's author - no Kling account exists for
this project yet, and the owner's standing rule forbids any paid call
without their explicit yes. Every request shape below is copied from
Kling's official docs as rendered on 2026-10-25:

- Auth: header "Authorization: Bearer <API Key>", domain
  https://api-singapore.klingai.com
  (kling.ai/document-api/api/get-started/authentication).
- Step 1, motion: POST /image-to-video/kling-3.0 with
  contents=[{type: prompt}, {type: first_frame}], settings={resolution,
  duration 3..15, audio "off", multi_shot false}; polled with
  GET /tasks?task_ids=<id> until status "succeeded"/"failed"
  (kling.ai/document-api/api/video/3-0-omni).
- Step 2, face: POST /v1/videos/identify-face with the generated
  video_id -> session_id + face_data[{face_id, start_time, end_time}]
  (kling.ai/document-api/api/video/lip-sync/face-detection).
- Step 3, lips: POST /v1/videos/advanced-lip-sync with session_id and ONE
  face_choose entry carrying the audio as sound_file; polled with
  GET /v1/videos/advanced-lip-sync/<id> until task_status "succeed"/
  "failed" (note: "succeed", not "succeeded", on this older endpoint)
  (kling.ai/document-api/api/video/lip-sync).

NOT verified, and only one real test shot can settle each:
- whether first_frame accepts raw Base64 (the docs say "URL or Base64";
  the Avatar endpoint's docs say raw Base64 without a data: prefix, which
  is what is sent here);
- whether a video_id from the newer /image-to-video endpoint is accepted
  by identify-face (its docs only say "the ID of the video generated by
  Kling AI");
- how well the lips follow ARABIC speech - Kling's docs name no language;
- how well lip sync holds on a moving, small or side-on face.
Kling's docs also state lip sync supports one person per task.

Pricing (kling.ai/dev/pricing, 2026-10-25), in units: Kling 3.0 without
native audio 0.6/s at 720p, 0.8/s at 1080p; Face Recognition 0.05 per
call; Lip Sync 0.5 per 5 seconds. One unit is $0.14 in the 180-day packs,
$0.098 in the trial pack. The real cost of each clip is read from the
deductions Kling's own responses report (billing / final_unit_deduction);
the table is only a fallback when a response omits them, and then the
lip-sync seconds are rounded UP to whole 5s blocks (Kling does not say
how it rounds - up is the safe side for a spend ceiling).
"""
from __future__ import annotations

import base64
import math
import subprocess
import tempfile
import time

from src.integrations.replicate_video_client import ReplicateVideoClient, ReplicateVideoError

BASE_URL = "https://api-singapore.klingai.com"

VIDEO_UNITS_PER_SECOND = {"720p": 0.6, "1080p": 0.8}
FACE_UNITS_PER_CALL = 0.05
LIP_SYNC_UNITS_PER_5S = 0.5
# 180-day pack price (kling.ai/dev/pricing, 2026-10-25). The trial pack is
# $0.098 - Settings.kling_unit_price_usd is the knob actually used.
DEFAULT_UNIT_PRICE_USD = 0.14

# Kling 3.0's duration enum (3..15 s) and Lip Sync's audio limits
# (2..60 s, <= 5MB) from the docs above.
MIN_VIDEO_SECONDS = 3
MAX_VIDEO_SECONDS = 15
MIN_AUDIO_SECONDS = 2.0
MAX_AUDIO_BYTES = 5 * 1024 * 1024

POLL_TIMEOUT_S = 1800


class KlingVideoError(ReplicateVideoError):
    pass


class KlingBalanceError(KlingVideoError):
    """Kling answered service code 1101/1102: the account is in arrears or
    the resource pack is exhausted/expired. No later line can succeed."""


def estimated_price_per_second_usd(unit_price_usd: float, resolution: str = "720p") -> float:
    """The pre-Approve estimate rate: motion + lip sync per second of clip.
    The one face-recognition call per clip is left out here; the real
    per-clip cost (last_cost_usd) includes it."""
    return (VIDEO_UNITS_PER_SECOND[resolution] + LIP_SYNC_UNITS_PER_5S / 5) * unit_price_usd


def _decode_data_uri(data_uri: str) -> tuple[bytes, str]:
    header, _, b64 = data_uri.partition(",")
    if not header.startswith("data:") or ";base64" not in header:
        raise KlingVideoError(f"not a base64 data URI: {data_uri[:60]!r}")
    return base64.b64decode(b64), header[len("data:"):].split(";", 1)[0]


def _probe_duration_seconds(audio_bytes: bytes) -> float:
    with tempfile.NamedTemporaryFile(suffix=".audio") as tmp:
        tmp.write(audio_bytes)
        tmp.flush()
        result = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "default=noprint_wrappers=1:nokey=1", tmp.name],
            capture_output=True, text=True,
        )
    if result.returncode != 0 or not result.stdout.strip():
        raise KlingVideoError(f"ffprobe failed on the real TTS audio: {result.stderr[-500:]}")
    return float(result.stdout.strip())


def _float_or_none(value) -> float | None:
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


class KlingVideoClient(ReplicateVideoClient):
    def __init__(
        self,
        api_key: str,
        *,
        unit_price_usd: float = DEFAULT_UNIT_PRICE_USD,
        resolution: str = "720p",
        http_client=None,
        poll_interval_seconds: float = 5,
        timeout_seconds: float = POLL_TIMEOUT_S,
        sleep=time.sleep,
        clock=time.monotonic,
    ):
        if resolution not in VIDEO_UNITS_PER_SECOND:
            raise ValueError(f"unsupported Kling resolution {resolution!r}")
        self._api_key = api_key
        self._unit_price_usd = unit_price_usd
        self._resolution = resolution
        self._http = http_client
        self._poll_interval_seconds = poll_interval_seconds
        self._timeout_seconds = timeout_seconds
        self._sleep = sleep
        self._clock = clock
        self._last_cost_usd: float | None = None

    def last_cost_usd(self) -> float | None:
        return self._last_cost_usd

    def generate_speech_to_video(
        self, *, prompt: str, image_data_uri: str, audio_data_uri: str, resolution: str = "480p"
    ) -> bytes:
        # `resolution` is the pipeline's Wan-era value ("480p"), which Kling
        # does not offer; this client's own configured resolution is used.
        self._last_cost_usd = None
        image_bytes, _ = _decode_data_uri(image_data_uri)
        audio_bytes, _ = _decode_data_uri(audio_data_uri)
        audio_seconds = _probe_duration_seconds(audio_bytes)

        # Every check that can fail is done before the first paid call.
        if audio_seconds < MIN_AUDIO_SECONDS:
            raise KlingVideoError(
                f"لم يُنفَّذ (بدون أي تكلفة): مدة الصوت {audio_seconds:.2f} ث أقل من الحد الأدنى لمزامنة الشفاه في Kling (2 ث)"
            )
        if audio_seconds > MAX_VIDEO_SECONDS:
            raise KlingVideoError(
                f"لم يُنفَّذ (بدون أي تكلفة): مدة الصوت {audio_seconds:.2f} ث أطول من أقصى مدة لقطة في Kling 3.0 (15 ث)"
            )
        if len(audio_bytes) > MAX_AUDIO_BYTES:
            raise KlingVideoError("لم يُنفَّذ (بدون أي تكلفة): ملف الصوت أكبر من 5MB، الحد الأقصى لمزامنة الشفاه في Kling")
        video_seconds = max(MIN_VIDEO_SECONDS, math.ceil(audio_seconds))

        units = 0.0
        cash_usd = 0.0

        # Step 1: the moving shot, silent.
        created = self._call("POST", "/image-to-video/kling-3.0", json={
            "contents": [
                {"type": "prompt", "text": prompt},
                {"type": "first_frame", "url": base64.b64encode(image_bytes).decode("ascii")},
            ],
            "settings": {
                "resolution": self._resolution,
                "duration": video_seconds,
                "audio": "off",
                "multi_shot": False,
            },
        })
        task_id = created["data"]["id"]
        task = self._wait(
            lambda: self._call("GET", "/tasks", params={"task_ids": task_id})["data"][0],
            status_key="status", done="succeeded", what=f"Kling 3.0 video task {task_id}",
        )
        video_units, video_cash = self._task_billing(task)
        if video_units is None and video_cash is None:
            units += VIDEO_UNITS_PER_SECOND[self._resolution] * video_seconds
        else:
            units += video_units or 0.0
            cash_usd += video_cash or 0.0
        video = next((o for o in task.get("outputs", []) if o.get("type") == "video"), None)
        if video is None or not video.get("id"):
            self._last_cost_usd = self._usd(units, cash_usd)
            raise KlingVideoError(f"المهمة {task_id} لم تُرجع فيديو: {task!r}")

        try:
            # Step 2: find the face to sync.
            face_resp = self._call("POST", "/v1/videos/identify-face", json={"video_id": video["id"]})["data"]
            units, cash_usd = self._add_deduction(face_resp, units, cash_usd, fallback_units=FACE_UNITS_PER_CALL)
            faces = face_resp.get("face_data") or []
            if not faces:
                raise KlingVideoError(
                    f"لم يجد Kling أي وجه في اللقطة {video['id']} لمزامنة الشفاه"
                )
            face = max(faces, key=lambda f: f.get("end_time", 0) - f.get("start_time", 0))

            # Step 3: lips on that face, audio placed where the face is.
            audio_ms = int(audio_seconds * 1000)
            video_ms = video_seconds * 1000
            insert_ms = max(0, min(int(face.get("start_time", 0)), video_ms - audio_ms))
            lip = self._call("POST", "/v1/videos/advanced-lip-sync", json={
                "session_id": face_resp["session_id"],
                "face_choose": [{
                    "face_id": face["face_id"],
                    "sound_file": base64.b64encode(audio_bytes).decode("ascii"),
                    "sound_start_time": 0,
                    "sound_end_time": audio_ms,
                    "sound_insert_time": insert_ms,
                }],
            })["data"]
            lip_id = lip["task_id"]
            lip_task = self._wait(
                lambda: self._call("GET", f"/v1/videos/advanced-lip-sync/{lip_id}")["data"],
                status_key="task_status", done="succeed", what=f"Kling lip-sync task {lip_id}",
            )
            units, cash_usd = self._add_deduction(
                lip_task, units, cash_usd, fallback_units=LIP_SYNC_UNITS_PER_5S * math.ceil(audio_seconds / 5)
            )
            try:
                url = lip_task["task_result"]["videos"][0]["url"]
            except (KeyError, IndexError, TypeError) as exc:
                raise KlingVideoError(f"Kling lip-sync task {lip_id} had no video URL: {lip_task!r}") from exc
            return self._download(url)
        finally:
            self._last_cost_usd = self._usd(units, cash_usd)

    def _usd(self, units: float, cash_usd: float) -> float:
        return units * self._unit_price_usd + cash_usd

    @staticmethod
    def _task_billing(task: dict) -> tuple[float | None, float | None]:
        units = cash = None
        for entry in task.get("billing") or []:
            amount = _float_or_none(entry.get("amount"))
            if amount is None:
                continue
            if entry.get("charge_type") == "unit":
                units = (units or 0.0) + amount
            elif entry.get("charge_type") == "cash" and entry.get("currency") == "USD":
                cash = (cash or 0.0) + amount
        return units, cash

    @staticmethod
    def _add_deduction(data: dict, units: float, cash_usd: float, *, fallback_units: float) -> tuple[float, float]:
        reported_units = _float_or_none(data.get("final_unit_deduction"))
        reported_cash = _float_or_none((data.get("final_balance_deduction") or {}).get("quota"))
        if reported_units is None and reported_cash is None:
            return units + fallback_units, cash_usd
        return units + (reported_units or 0.0), cash_usd + (reported_cash or 0.0)

    def _wait(self, fetch, *, status_key: str, done: str, what: str) -> dict:
        deadline = self._clock() + self._timeout_seconds
        while True:
            task = fetch()
            status = task.get(status_key)
            if status == done:
                return task
            if status == "failed":
                reason = task.get("message") or task.get("task_status_msg") or ""
                raise KlingVideoError(f"{what} failed: {reason}")
            if self._clock() >= deadline:
                raise KlingVideoError(f"{what} did not finish within {self._timeout_seconds:.0f}s (last status {status!r})")
            self._sleep(self._poll_interval_seconds)

    def _client(self):
        if self._http is None:
            import httpx

            self._http = httpx.Client(base_url=BASE_URL, timeout=60)
        return self._http

    def _call(self, method: str, path: str, *, json: dict | None = None, params: dict | None = None) -> dict:
        resp = self._client().request(
            method, path, json=json, params=params,
            headers={"Authorization": f"Bearer {self._api_key}", "Content-Type": "application/json"},
        )
        try:
            body = resp.json()
        except ValueError:
            body = {}
        code = body.get("code") if isinstance(body, dict) else None
        if code in (1101, 1102):
            raise KlingBalanceError(f"Kling account cannot pay ({resp.status_code}, code {code}): {body.get('message', '')}")
        if resp.status_code >= 400 or code not in (0, None):
            raise KlingVideoError(f"Kling {method} {path} failed ({resp.status_code}, code {code}): {resp.text[:500]}")
        return body

    def _download(self, url: str) -> bytes:
        resp = self._client().get(url, timeout=120)
        if resp.status_code >= 400:
            raise KlingVideoError(f"تعذّر تنزيل فيديو Kling ({resp.status_code})")
        return resp.content
